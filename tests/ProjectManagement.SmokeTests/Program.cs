// Integration checks use a new temporary database, never the application database.
internal static class Program
{
    private static int checkCount;

    [STAThread]
    private static void Main()
    {
        string root = Directory.GetCurrentDirectory();
        if (!File.Exists(Path.Combine(root, "HumanResourceManagement.sln")))
            throw new InvalidOperationException("Run this project from the repository root.");

        string databaseName = "HrmProjectManagementSmoke_" + Guid.NewGuid().ToString("N");
        SqlConnectionStringBuilder settings = new SqlConnectionStringBuilder
        {
            DataSource = Environment.GetEnvironmentVariable("HRM_TEST_SERVER") ?? "localhost",
            InitialCatalog = "master", IntegratedSecurity = true,
            Encrypt = true, TrustServerCertificate = true, ConnectTimeout = 5
        };
        string masterConnection = settings.ConnectionString;
        bool databaseCreated = false;
        try
        {
            execute(masterConnection, "CREATE DATABASE [" + databaseName + "]");
            databaseCreated = true;
            settings.InitialCatalog = databaseName;
            string connectionString = settings.ConnectionString;

            string baseSchema = File.ReadAllText(Path.Combine(root, "database/01_CreateDatabase.sql"));
            baseSchema = baseSchema[baseSchema.IndexOf("CREATE TABLE dbo.Departments", StringComparison.Ordinal)..];
            executeScript(connectionString, baseSchema);
            foreach (string file in new[] { "02_SeedData.sql", "03_ProjectManagement.sql", "04_ProjectManagementSeed.sql",
                "03_ProjectManagement.sql", "04_ProjectManagementSeed.sql" })
            {
                string script = File.ReadAllText(Path.Combine(root, "database", file));
                executeScript(connectionString, script.Replace("USE HumanResourceManagement;", "USE [" + databaseName + "];"));
            }
            check(scalar(connectionString, "SELECT COUNT(*) FROM dbo.Projects") == 1, "seed scripts can run twice");
            runChecks(connectionString);
            Console.WriteLine("PASS: " + checkCount + " checks. Screenshots: " + Path.Combine(AppContext.BaseDirectory, "screenshots"));
        }
        finally
        {
            if (databaseCreated)
            {
                SqlConnection.ClearAllPools();
                // Only the exact database name generated by this process may be removed.
                string suffix = databaseName["HrmProjectManagementSmoke_".Length..];
                if (!Guid.TryParseExact(suffix, "N", out _))
                    throw new InvalidOperationException("Unexpected test database name.");
                execute(masterConnection, "ALTER DATABASE [" + databaseName + "] SET SINGLE_USER WITH ROLLBACK IMMEDIATE; DROP DATABASE [" + databaseName + "];");
                Console.WriteLine("Removed temporary test database.");
            }
        }
    }

    private static void runChecks(string connectionString)
    {
        var projects = ServiceFactory.createProjectBus(connectionString);
        var details = ServiceFactory.createProjectDetailBus(connectionString);
        var tasks = ServiceFactory.createProjectTaskBus(connectionString);
        var assignments = ServiceFactory.createAssignmentBus(connectionString);
        var lookups = ServiceFactory.createProjectLookupBus(connectionString);
        var factory = new MyConnection(connectionString);
        var assignmentDao = new AssignmentDao(factory);
        var taskDao = new ProjectTaskDao(factory);
        var detailDao = new ProjectDetailDao(factory);
        int departmentId = lookups.getDepartments()[0].id;
        int employeeId = lookups.getEmployees()[0].id;

        ProjectDto project = makeProject("Nhóm 'A' – C# cơ bản", departmentId, employeeId);
        projects.add(project);
        check(project.id > 0, "project identity generated");
        ProjectDto storedProject = (ProjectDto)projects.search("Nhóm 'A'")[0]!;
        check(storedProject.name == project.name && storedProject.budget == 1234567.89m && storedProject.endDate == null,
            "Unicode, apostrophe, decimal and nullable date round trip");
        check(projects.search("NHÓM 'A'").Count == 1, "case insensitive ArrayList search");
        check(projects.search("no_such_keyword_524").Count == 0, "search no matches");

        ProjectDto invalidProject = makeProject(" ", departmentId, employeeId);
        expectFailure(() => projects.add(invalidProject), "blank project name");
        invalidProject.name = "Invalid";
        invalidProject.deadline = invalidProject.startDate.AddDays(-1);
        expectFailure(() => projects.add(invalidProject), "deadline before start");
        invalidProject.deadline = project.deadline;
        invalidProject.endDate = project.startDate.AddDays(-1);
        expectFailure(() => projects.add(invalidProject), "end date before start");
        invalidProject.endDate = null;
        invalidProject.budget = -1;
        expectFailure(() => projects.add(invalidProject), "negative budget");
        invalidProject.budget = 1.001m;
        expectFailure(() => projects.add(invalidProject), "excess decimal precision");
        invalidProject.budget = 1;
        invalidProject.departmentId = 0;
        expectFailure(() => projects.add(invalidProject), "missing department");
        invalidProject.departmentId = departmentId;
        invalidProject.managerId = 0;
        expectFailure(() => projects.add(invalidProject), "missing manager");
        invalidProject.managerId = employeeId;
        invalidProject.name = new string('a', 151);
        expectFailure(() => projects.add(invalidProject), "text length");
        invalidProject.name = "Invalid";
        invalidProject.status = "unknown";
        expectFailure(() => projects.add(invalidProject), "unknown status");

        ProjectDto otherProject = makeProject("Dự án thứ hai", departmentId, employeeId);
        ProjectDto thirdProject = makeProject("Dự án thứ ba", departmentId, employeeId);
        projects.add(otherProject);
        projects.add(thirdProject);
        ProjectDetailDto detail = new ProjectDetailDto { projectId = project.id, allowance = 100, reward = 200 };
        details.add(detail);
        var cachedDetails = details.getAll();
        int detailCount = cachedDetails.Count;
        expectFailure(() => details.add(new ProjectDetailDto { projectId = project.id }), "one detail per project in BUS");
        check(cachedDetails.Count == detailCount, "failed save leaves ArrayList unchanged");
        expectFailure(() => detailDao.add(new ProjectDetailDto { projectId = project.id }), "one detail per project in database");
        expectFailure(() => details.add(new ProjectDetailDto { projectId = 0 }), "missing project");
        ProjectDetailDto otherDetail = new ProjectDetailDto { projectId = otherProject.id };
        details.add(otherDetail);

        ProjectTaskDto task = makeTask(detail.id, "Kiểm thử 'GUI'");
        ProjectTaskDto secondTask = makeTask(detail.id, "Kiểm thử BUS");
        tasks.add(task);
        tasks.add(secondTask);
        check(tasks.getByProjectDetail(detail.id).Count == 2, "one detail has multiple tasks");
        check(tasks.getProjectId(task.id) == project.id, "resolve task project");
        ProjectTaskDto invalidTask = makeTask(0, "Invalid");
        expectFailure(() => tasks.add(invalidTask), "missing detail");
        invalidTask.projectDetailId = detail.id;
        invalidTask.completionRate = 101;
        expectFailure(() => tasks.add(invalidTask), "progress above 100");
        invalidTask.completionRate = -1;
        expectFailure(() => tasks.add(invalidTask), "negative progress");
        invalidTask.completionRate = 0;
        invalidTask.priority = "unknown";
        expectFailure(() => tasks.add(invalidTask), "unknown priority");
        invalidTask.priority = "Normal";
        invalidTask.estimatedHours = -1;
        expectFailure(() => tasks.add(invalidTask), "negative hours");

        AssignmentDto assignment = new AssignmentDto
        {
            projectId = project.id, taskId = task.id, employeeId = employeeId,
            assignedDate = task.startDate, startDate = task.startDate, deadline = task.deadline,
            notes = "Phân công 'A'"
        };
        assignments.add(assignment);
        check(assignments.search("Phân công 'A'").Count == 1, "assignment search");
        expectFailure(() => assignments.add(new AssignmentDto
        {
            projectId = otherProject.id, taskId = task.id, employeeId = employeeId,
            assignedDate = task.startDate, startDate = task.startDate, deadline = task.deadline
        }), "wrong project rejected by BUS");
        expectFailure(() => assignmentDao.add(new AssignmentDto
        {
            projectId = otherProject.id, taskId = secondTask.id, employeeId = employeeId,
            assignedDate = task.startDate, startDate = task.startDate, deadline = task.deadline
        }), "wrong project rejected by SQL trigger");
        AssignmentDto duplicate = new AssignmentDto
        {
            projectId = project.id, taskId = task.id, employeeId = employeeId,
            assignedDate = task.startDate, startDate = task.startDate, deadline = task.deadline
        };
        expectFailure(() => assignments.add(duplicate), "duplicate assignment in BUS");
        expectFailure(() => assignmentDao.add(duplicate), "duplicate assignment in database");
        duplicate.taskId = secondTask.id;
        duplicate.assignedDate = duplicate.startDate.AddDays(1);
        expectFailure(() => assignments.add(duplicate), "assignment date after start");
        duplicate.assignedDate = duplicate.startDate;
        duplicate.employeeId = 0;
        expectFailure(() => assignments.add(duplicate), "missing employee");
        duplicate.employeeId = employeeId;
        duplicate.contributionScore = -1;
        expectFailure(() => assignments.add(duplicate), "negative contribution score");

        task.projectDetailId = otherDetail.id;
        expectFailure(() => tasks.update(task), "cannot move assigned task to another project");
        check(tasks.getProjectId(task.id) == project.id, "task move rolled back");
        task.projectDetailId = detail.id;
        detail.projectId = thirdProject.id;
        expectFailure(() => details.update(detail), "cannot move assigned detail to another project");
        detail.projectId = project.id;

        project.name = "Đã sửa 'A'";
        project.endDate = project.startDate.AddDays(60);
        projects.update(project);
        check(((ProjectDto)projects.search("Đã sửa 'A'")[0]!).endDate == project.endDate, "update project");
        project.endDate = null;
        projects.update(project);
        check(((ProjectDto)projects.search("Đã sửa 'A'")[0]!).endDate == null, "clear optional end date");
        detail.completionRate = 25;
        detail.allowance = 300;
        details.update(detail);
        check(details.search(detail.id.ToString()).Count > 0, "detail search");
        task.name = "Công việc đã sửa";
        task.completionRate = 100;
        task.status = "Completed";
        task.completedDate = task.deadline.AddDays(1);
        tasks.update(task);
        check(((ProjectTaskDto)tasks.search("Công việc đã sửa")[0]!).completedDate == task.completedDate,
            "task update allows completion after deadline");
        task.completedDate = null;
        task.status = "In progress";
        task.completionRate = 50;
        tasks.update(task);
        check(((ProjectTaskDto)tasks.search("Công việc đã sửa")[0]!).completedDate == null, "clear optional completed date");
        assignment.completionRate = 50;
        assignment.contributionScore = 8.5m;
        assignment.status = "In progress";
        assignments.update(assignment);
        check(((AssignmentDto)assignments.search("Phân công 'A'")[0]!).contributionScore == 8.5m, "assignment update");

        check(scalar(connectionString, "SELECT COUNT(*) FROM dbo.Payroll") == 0, "project money does not change payroll");
        renderForms(connectionString, project.id, assignment.id);

        expectFailure(() => projects.delete(project.id), "cannot delete project with detail");
        expectFailure(() => details.delete(detail.id), "cannot delete detail with tasks");
        expectFailure(() => tasks.delete(task.id), "cannot delete task with assignments");
        expectFailure(() => assignments.delete(0), "invalid delete id");
        assignments.delete(assignment.id);
        expectFailure(() => assignments.update(assignment), "update deleted assignment");
        tasks.delete(task.id);
        tasks.delete(secondTask.id);
        check(tasks.getByProjectDetail(detail.id).Count == 0, "delete tasks");
        details.delete(detail.id);
        details.delete(otherDetail.id);
        projects.delete(project.id);
        projects.delete(otherProject.id);
        projects.delete(thirdProject.id);
        expectFailure(() => projects.delete(project.id), "delete nonexistent project");
        check(projects.search("Đã sửa 'A'").Count == 0, "delete project");
    }

    private static ProjectDto makeProject(string name, int departmentId, int employeeId)
    {
        return new ProjectDto
        {
            name = name, startDate = new DateTime(2026, 11, 1), deadline = new DateTime(2026, 12, 31),
            description = "SQL 'quoted' và tiếng Việt", budget = 1234567.89m,
            departmentId = departmentId, managerId = employeeId
        };
    }

    private static ProjectTaskDto makeTask(int detailId, string name)
    {
        return new ProjectTaskDto
        {
            projectDetailId = detailId, name = name, startDate = new DateTime(2026, 11, 2),
            deadline = new DateTime(2026, 11, 30), estimatedHours = 12.5m
        };
    }

    private static void renderForms(string connectionString, int projectId, int assignmentId)
    {
        ApplicationConfiguration.Initialize();
        string output = Path.Combine(AppContext.BaseDirectory, "screenshots");
        Directory.CreateDirectory(output);
        using ProjectForm projectForm = new ProjectForm(ServiceFactory.createProjectBus(connectionString),
            ServiceFactory.createProjectDetailBus(connectionString), ServiceFactory.createProjectTaskBus(connectionString),
            ServiceFactory.createProjectLookupBus(connectionString));
        using ProjectDetailForm detailForm = new ProjectDetailForm(ServiceFactory.createProjectDetailBus(connectionString),
            ServiceFactory.createProjectBus(connectionString));
        using ProjectTaskForm taskForm = new ProjectTaskForm(ServiceFactory.createProjectTaskBus(connectionString),
            ServiceFactory.createProjectDetailBus(connectionString));
        using AssignmentForm assignmentForm = new AssignmentForm(ServiceFactory.createAssignmentBus(connectionString),
            ServiceFactory.createProjectBus(connectionString), ServiceFactory.createProjectDetailBus(connectionString),
            ServiceFactory.createProjectTaskBus(connectionString), ServiceFactory.createProjectLookupBus(connectionString));
        foreach (Form form in new Form[] { projectForm, detailForm, taskForm, assignmentForm })
        {
            // Render the test window outside the visible desktop area.
            form.ShowInTaskbar = false;
            form.StartPosition = FormStartPosition.Manual;
            form.Location = new Point(-20000, -20000);
            form.Show();
            Application.DoEvents();
            ListView list = (ListView)form.GetType().GetField("itemListView", BindingFlags.Instance | BindingFlags.NonPublic)!.GetValue(form)!;
            int targetId = form == projectForm ? projectId : form == assignmentForm ? assignmentId : 0;
            foreach (ListViewItem row in list.Items)
            {
                if (row.Text == targetId.ToString())
                {
                    row.Selected = true;
                    break;
                }
            }
            Application.DoEvents();
            if (targetId != 0)
            {
                int selectedId = (int)form.GetType().GetField("selectedId", BindingFlags.Instance | BindingFlags.NonPublic)!.GetValue(form)!;
                check(selectedId == targetId, form.GetType().Name + " selection fills editor");
            }
            if (form == projectForm)
            {
                ListView taskList = (ListView)form.GetType().GetField("taskListView", BindingFlags.Instance | BindingFlags.NonPublic)!.GetValue(form)!;
                check(taskList.Items.Count == 2, "project main-sub list shows its tasks");
            }
            if (form == assignmentForm)
            {
                ComboBox projectCombo = (ComboBox)form.GetType().GetField("projectIdComboBox", BindingFlags.Instance | BindingFlags.NonPublic)!.GetValue(form)!;
                ComboBox taskCombo = (ComboBox)form.GetType().GetField("taskIdComboBox", BindingFlags.Instance | BindingFlags.NonPublic)!.GetValue(form)!;
                check(taskCombo.Items.Count == 2, "assignment task choices match project");
                projectCombo.SelectedIndex = -1;
                check(taskCombo.Items.Count == 0, "clearing project clears task choices");
                for (int index = 0; index < projectCombo.Items.Count; index++)
                {
                    if (((DTO.ProjectManagement.LookupItemDto)projectCombo.Items[index]!).id == projectId)
                        projectCombo.SelectedIndex = index;
                }
                form.GetType().GetMethod("itemSelectionChanged", BindingFlags.Instance | BindingFlags.NonPublic)!.Invoke(form, new object?[] { null, EventArgs.Empty });
            }
            form.Refresh();
            using Bitmap bitmap = new Bitmap(form.Width, form.Height);
            form.DrawToBitmap(bitmap, new Rectangle(Point.Empty, form.Size));
            bitmap.Save(Path.Combine(output, form.GetType().Name + ".png"));
            check(list.Items.Count > 0, form.GetType().Name + " loads rows");
            form.Hide();
        }
    }

    private static void check(bool condition, string name)
    {
        if (!condition)
            throw new InvalidOperationException("FAIL: " + name);
        checkCount++;
        Console.WriteLine("PASS: " + name);
    }

    private static void expectFailure(Action action, string name)
    {
        try { action(); }
        catch (Exception exception) when (exception is ArgumentException || exception is InvalidOperationException)
        {
            check(true, name);
            return;
        }
        throw new InvalidOperationException("FAIL: " + name + " did not fail");
    }

    private static void execute(string connectionString, string sql)
    {
        using SqlConnection connection = new SqlConnection(connectionString);
        connection.Open();
        using SqlCommand command = new SqlCommand(sql, connection) { CommandTimeout = 30 };
        command.ExecuteNonQuery();
    }

    private static int scalar(string connectionString, string sql)
    {
        using SqlConnection connection = new SqlConnection(connectionString);
        connection.Open();
        using SqlCommand command = new SqlCommand(sql, connection);
        return Convert.ToInt32(command.ExecuteScalar());
    }

    private static void executeScript(string connectionString, string script)
    {
        foreach (string batch in Regex.Split(script, @"^\s*GO\s*$", RegexOptions.Multiline | RegexOptions.IgnoreCase))
        {
            if (!string.IsNullOrWhiteSpace(batch))
                execute(connectionString, batch);
        }
    }
}
